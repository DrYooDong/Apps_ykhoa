-- ==============================================================================
-- 4. Bảng SOAP Clinical Experiences (Sổ tay Đúc kết Kinh nghiệm Lâm sàng Chuẩn SOAP)
-- Lưu ý: Không lưu trữ thông tin nhận diện bệnh nhân (Không có họ tên, CMND, địa chỉ)
-- ==============================================================================
create table if not exists public.soap_clinical_experiences (
  id text primary key,
  title text not null,
  specialty text not null default 'Tim mạch',
  experience_level text not null default 'essential', -- 'essential' | 'pitfall' | 'rare' | 'advanced'
  tags jsonb default '[]'::jsonb,
  demographic_context text, -- Ví dụ: "Bệnh nhân 68 tuổi, tiền căn ĐTĐ 12 năm"
  author_doctor text default 'Bác sĩ lâm sàng',
  is_favorite boolean default false,
  view_count integer default 0,
  source_reference text, -- Guideline, Sách, Ca lâm sàng thực tế
  clinical_context text default 'Khoa Cấp cứu', -- Bối cảnh khoa phòng
  difficulty_rating integer default 3 check (difficulty_rating between 1 and 5), -- Độ khó 1-5
  outcome_notes text, -- Kết cục ca bệnh & Di chứng nếu có
  s jsonb not null default '{}'::jsonb, -- Subjective
  o jsonb not null default '{}'::jsonb, -- Objective
  a jsonb not null default '{}'::jsonb, -- Assessment
  p jsonb not null default '{}'::jsonb, -- Plan
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- Bổ sung cột cho table đã tạo từ trước (Migration Safe)
alter table public.soap_clinical_experiences
  add column if not exists view_count integer default 0,
  add column if not exists source_reference text,
  add column if not exists clinical_context text default 'Khoa Cấp cứu',
  add column if not exists difficulty_rating integer default 3 check (difficulty_rating between 1 and 5),
  add column if not exists outcome_notes text;

create index if not exists idx_soap_specialty on public.soap_clinical_experiences(specialty);
create index if not exists idx_soap_level on public.soap_clinical_experiences(experience_level);
create index if not exists idx_soap_created on public.soap_clinical_experiences(created_at desc);
create index if not exists idx_soap_tags on public.soap_clinical_experiences using gin(tags);

alter table public.soap_clinical_experiences enable row level security;
create policy "Allow all access to soap_clinical_experiences" on public.soap_clinical_experiences for all using (true) with check (true);

