-- ==============================================================================
-- MedLens DocSpace Pro — Supabase Database Schema
-- Tích hợp Hồ sơ Bác sĩ, Quản lý Bệnh nhân & Bệnh án Lâm sàng MedLens
-- ==============================================================================

-- 1. Bảng Doctors (Hồ sơ Bác sĩ)
create table if not exists public.doctors (
  id uuid primary key default gen_random_uuid(),
  uid text unique not null,
  email text unique not null,
  name text not null default 'Bác sĩ lâm sàng',
  role text not null default 'doctor',
  specialty text default 'Nội tổng quát & Cấp cứu',
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- 2. Bảng Patients (Danh mục Bệnh nhân)
create table if not exists public.patients (
  id bigint generated by default as identity primary key,
  patient_code text unique not null,
  full_name text not null,
  gender text not null default 'nam', -- 'nam' | 'nu' | 'khac'
  age integer,
  occupation text,
  phone_number text,
  id_card text,
  address text,
  notes text,
  created_by_uid text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- 3. Bảng Medical Records (Hồ sơ Bệnh án & Kết quả Phân tích MedLens)
create table if not exists public.medical_records (
  id bigint generated by default as identity primary key,
  record_code text unique not null,
  patient_id bigint references public.patients(id) on delete set null,
  patient_code text not null,
  patient_name text not null,
  gender text not null default 'nam',
  age integer,
  occupation text,
  doctor_uid text not null default 'dr_default',
  doctor_name text default 'Bác sĩ lâm sàng',
  admission_reason text,
  clinical_summary text,
  vitals jsonb default '{}'::jsonb,
  labs jsonb default '{}'::jsonb,
  selected_symptoms jsonb default '[]'::jsonb,
  derived_symptoms jsonb default '[]'::jsonb,
  negated_symptoms jsonb default '[]'::jsonb,
  free_texts jsonb default '{}'::jsonb,
  primary_diagnosis jsonb default '{}'::jsonb,
  differential_diagnoses jsonb default '[]'::jsonb,
  treatment_protocol jsonb default '{}'::jsonb,
  status text not null default 'hoan_tat', -- 'dang_kham' | 'hoan_tat' | 'chuyen_vien'
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- Indexes tối ưu truy vấn
create index if not exists idx_patients_code on public.patients(patient_code);
create index if not exists idx_patients_name on public.patients(full_name);
create index if not exists idx_records_code on public.medical_records(record_code);
create index if not exists idx_records_patient_code on public.medical_records(patient_code);
create index if not exists idx_records_doctor on public.medical_records(doctor_uid);
create index if not exists idx_records_created on public.medical_records(created_at desc);

-- Row Level Security (RLS)
alter table public.doctors enable row level security;
alter table public.patients enable row level security;
alter table public.medical_records enable row level security;

-- Policies: Cho phép đọc/ghi qua Anon key và Authenticated user (Client-friendly)
create policy "Allow all access to doctors" on public.doctors for all using (true) with check (true);
create policy "Allow all access to patients" on public.patients for all using (true) with check (true);
create policy "Allow all access to medical_records" on public.medical_records for all using (true) with check (true);

